// Build a shareable "model card" from a model's metadata (the saved-model
// sidecar, or a live studio model). Pure helpers shared by the card UI and the
// Markdown export so the two never drift.

// one-line "what is this model" for lists (works for registry rows and engine sidecars)
export function describeModel(m) {
  const base = m.base_model || m.base;
  if (m.kind === "finetune") return `Fine-tune · ${base || "base model"}`;
  if (m.kind === "asr") return `Speech-to-text · ${base || "Whisper"}`;
  if (m.kind === "tts") return `Text-to-speech · ${base || "SpeechT5"}`;
  if (m.kind === "vlm") return `Image captioning · ${base || "vision model"}`;
  const t = { text: "Language model", copy: "Copy task", sort: "Sort task" }[m.template] || "Trained from scratch";
  return m.size ? `${t} · ${m.size}` : t;
}

export function modelCardRows(m) {
  const rows = [];
  if (m.template && m.kind !== "finetune") rows.push(["Template", m.template]);
  if (m.base_model) rows.push(["Base model", m.base_model]);
  if (m.method) rows.push(["Method", String(m.method).toUpperCase()]);
  if (m.size && m.kind !== "finetune") rows.push(["Size", m.size]);
  if (m.params_m) rows.push(["Parameters", `${m.params_m}M`]);
  if (m.n_experts > 1) rows.push(["Experts", `${m.n_experts} · top-${m.moe_top_k || 2}`]);
  if (m.tokenizer) rows.push(["Tokenizer", m.tokenizer + (m.vocab_size ? ` · vocab ${m.vocab_size}` : "")]);
  if (m.block_size) rows.push(["Context length", `${m.block_size} tokens`]);
  if (m.step) rows.push(["Trained steps", Number(m.step).toLocaleString()]);
  if (m.created) rows.push(["Created", new Date(m.created * 1000).toLocaleDateString()]);
  return rows;
}

export function dataSummary(d) {
  if (!d) return null;
  const parts = [];
  const n = (v) => Number(v).toLocaleString();
  if (d.documents != null) parts.push(`${n(d.documents)} docs`);
  if (d.chars != null) parts.push(`${n(d.chars)} chars`);
  if (d.est_tokens != null) parts.push(`~${n(d.est_tokens)} tokens`);
  return parts.join(" · ") || null;
}

// the generated continuation with the seed prompt stripped, if it's a prefix
export function sampleCont(s) {
  if (!s || typeof s === "string") return "";
  const c = s.cont || "";
  return s.prompt && c.startsWith(s.prompt) ? c.slice(s.prompt.length) : c;
}

// a safe, short seed prompt for the runnable snippet (no shell-breaking chars)
function samplePrompt(m) {
  const s = (m.samples || []).find(Boolean);
  const p = s && typeof s !== "string" ? s.prompt : "";
  return (p || "Hello").replace(/['"`\\\n]/g, " ").trim().slice(0, 40) || "Hello";
}

// ready-to-run code to call the model's hosted endpoint (deploy it first)
export function usageSnippet(m) {
  const prompt = samplePrompt(m);
  const base = (typeof import.meta !== "undefined" && import.meta.env?.VITE_API_URL) || "http://localhost:8000";
  return [
    `# Call "${m.name}" on your hosted endpoint (Deploy it from the dashboard,`,
    `# then create an API key). Requests are metered per call.`,
    `curl -s ${base}/v1/${m.name}/generate \\`,
    `  -H "Authorization: Bearer $FIDDLEHEAD_API_KEY" \\`,
    `  -d '{"prompt":"${prompt}","max_new_tokens":80}'`,
    ``,
    `# ...or from Python:`,
    `import requests`,
    `r = requests.post("${base}/v1/${m.name}/generate",`,
    `                  headers={"Authorization": "Bearer " + API_KEY},`,
    `                  json={"prompt": ${JSON.stringify(prompt)}, "max_new_tokens": 80})`,
    `print(r.json()["text"])`,
  ].join("\n");
}

export function kindLine(m) {
  return m.kind === "finetune"
    ? `Fine-tune of ${m.base_model || "a base model"}${m.method ? ` · ${String(m.method).toUpperCase()}` : ""}`
    : `From-scratch ${m.template || "text"} model`;
}

export function modelCardMarkdown(m) {
  const L = [];
  L.push(`# ${m.name}`, "");
  L.push(kindLine(m) + (m.params_m ? ` · ${m.params_m}M parameters` : ""), "");
  L.push("## Recipe", "", "| Field | Value |", "| --- | --- |");
  modelCardRows(m).forEach(([k, v]) => L.push(`| ${k} | ${v} |`));
  if (m.final_loss != null || m.eval) {
    L.push("", "## Metrics", "");
    if (m.final_loss != null) L.push(`- **Final loss:** ${Number(m.final_loss).toFixed(3)}`);
    if (m.eval?.headline) L.push(`- **Quality:** ${m.eval.headline}`);
  }
  const ds = dataSummary(m.data);
  if (ds) L.push("", "## Data", "", `- ${ds}`);
  const samples = (m.samples || []).filter(Boolean);
  if (samples.length) {
    L.push("", "## Sample output", "");
    samples.forEach((s) => {
      const text = typeof s === "string" ? s : `${s.prompt || ""}${sampleCont(s)}`;
      L.push("```", text.trim(), "```");
    });
  }
  L.push("", "## Usage", "", "```bash", usageSnippet(m), "```");
  L.push("", "_Generated by Fiddlehead._");
  return L.join("\n");
}
